package app.orchard.tv.quiz

import android.content.Context
import android.util.Log
import androidx.annotation.VisibleForTesting
import com.planyourtv.policy.TvStore
import com.planyourtv.policy.quiz.QuizItem
import com.planyourtv.policy.quiz.QuizSessionCodec
import org.json.JSONObject

/**
 * The questions shipped inside the APK.
 *
 * A fresh TV has no AI provider key and maybe no network, so without this the
 * local bank starts empty and the quiz row stays unavailable until a parent
 * generates a batch first. The asset is imported once per [SEED_VERSION] into
 * [QuizQuestionCache]; the marker keeps a deliberate "clear bank" cleared.
 * A later APK replaces the previous bundled set by bumping the version; rows
 * generated by the user are never deleted.
 *
 * Only the local source uses this bank. A TV bound to a family reads the
 * remote QB instead and is not affected.
 */
object QuizSeedBank {
    /** Bump together with assets/quiz/seed_bank.json. */
    const val SEED_VERSION = 2

    private const val TAG = "QuizSeedBank"
    private const val ASSET = "quiz/seed_bank.json"
    private const val KEY_VERSION = "quiz.seedBankVersion"

    /**
     * Imports the bundled bank when this process has not imported the current
     * seed version yet. Returns the number of questions added; 0 means already
     * imported, storage not ready, or the asset is unusable.
     *
     * Runs on the caller's thread: the asset is small and this happens once per
     * seed version, before the lock screen reads the bank for the first time.
     */
    fun install(context: Context): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        if (TvStore.getInt(KEY_VERSION, 0) >= SEED_VERSION) return 0
        val raw = runCatching {
            context.applicationContext.assets.open(ASSET).bufferedReader().use { it.readText() }
        }.getOrElse { error ->
            Log.e(TAG, "cannot read $ASSET", error)
            return 0
        }
        return importJson(raw, SEED_VERSION)
    }

    @VisibleForTesting
    internal fun importJson(
        raw: String,
        version: Int,
        nowMs: Long = System.currentTimeMillis(),
    ): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        if (version <= 0 || TvStore.getInt(KEY_VERSION, 0) >= version) return 0
        val array = runCatching { JSONObject(raw).optJSONArray("items") }.getOrNull()
        if (array == null) {
            Log.e(TAG, "seed bank v$version has no items array")
            return 0
        }
        val items = ArrayList<QuizItem>(array.length())
        var skipped = 0
        for (index in 0 until array.length()) {
            val encoded = array.optJSONObject(index)?.toString()
            val item = encoded?.let { QuizSessionCodec.decodeItem(it) }
            if (item == null) skipped++ else items += item
        }
        if (items.isEmpty()) {
            Log.e(TAG, "seed bank v$version has no valid items ($skipped skipped)")
            return 0
        }
        val result = QuizQuestionCache.replaceSeedQuestions("preset-v$version", items, nowMs)
        if (result.appended == 0 && result.duplicates == 0) {
            // Nothing usable made it in. Leave the marker unset so a later
            // start can retry instead of freezing an empty seed bank.
            Log.w(TAG, "seed bank v$version imported nothing: rejected=${result.rejected}")
            return 0
        }
        // A partial import (the bank is already full of user questions) still
        // marks the version. Otherwise every start would delete and reinsert
        // the same seed rows, resetting their answer history each time.
        TvStore.putInt(KEY_VERSION, version)
        TvStore.sync()
        Log.i(
            TAG,
            "seed bank v$version: appended=${result.appended} " +
                "duplicates=${result.duplicates} rejected=${result.rejected} skipped=$skipped",
        )
        return result.appended
    }

    @VisibleForTesting
    internal fun clearMarkerForTest() {
        TvStore.remove(KEY_VERSION)
    }
}
