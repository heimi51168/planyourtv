package app.orchard.tv.quiz

import android.content.Context
import android.util.JsonReader
import android.util.JsonToken
import android.util.Log
import androidx.annotation.VisibleForTesting
import com.planyourtv.policy.TvStore
import com.planyourtv.policy.quiz.QuizItem
import com.planyourtv.policy.quiz.QuizPresetBank
import com.planyourtv.policy.quiz.QuizSessionCodec
import org.json.JSONArray
import org.json.JSONObject
import java.io.FileNotFoundException
import java.io.Reader
import java.io.StringReader

/**
 * The questions shipped inside the APK.
 *
 * A fresh TV has no AI provider key and maybe no network, so without this the
 * local bank starts empty and the quiz row stays unavailable until a parent
 * generates a batch first. Each asset is imported once per its own version into
 * [QuizQuestionCache]; the marker keeps a deliberate "clear bank" cleared.
 * A later APK replaces the previous bundled set by bumping the version; rows
 * generated by the user are never deleted.
 *
 * The single- and multiple-choice questions live in separate assets with
 * separate markers and source tags. That way shipping the multiple-choice bank
 * does not reimport the 5500 single-choice rows or reset their answer history.
 *
 * Import streams the JSON with [JsonReader] and inserts one small batch at a
 * time, so a low-memory TV never holds the whole asset tree and decoded list in
 * memory at once. The semantics are unchanged: everything runs in one
 * transaction, and a malformed or unusable asset keeps the previous bank.
 *
 * Only the local source uses these banks. A TV bound to a family reads the
 * remote QB instead and is not affected.
 */
object QuizSeedBank {
    /** Bump together with assets/quiz/seed_bank.json. */
    const val SEED_VERSION = 4
    /** Bump together with assets/quiz/seed_bank_multi.json. */
    const val MULTI_SEED_VERSION = 1
    /** Bump together with assets/quiz/parent_fun_bank.json. */
    const val PARENT_FUN_VERSION = 1

    private const val TAG = "QuizSeedBank"
    private const val ASSET = "quiz/seed_bank.json"
    private const val MULTI_ASSET = "quiz/seed_bank_multi.json"
    private const val PARENT_FUN_ASSET = "quiz/parent_fun_bank.json"
    private const val KEY_VERSION = "quiz.seedBankVersion"
    private const val KEY_MULTI_VERSION = "quiz.seedMultiBankVersion"
    private const val KEY_PARENT_FUN_VERSION = "quiz.parentFunBankVersion"
    private const val SEED_TAG = "preset-v"
    private const val MULTI_SEED_TAG = "preset-multi-v"

    /**
     * Stable prefix of the parent life-knowledge bank. It must match
     * [QuizPresetBank.PARENT_LIFE] in `:policy`; existing `source_ref` values
     * depend on it, so changing it would orphan imported rows.
     */
    private const val PARENT_FUN_TAG = "preset:parent-life:"

    /**
     * Imports the bundled banks when this process has not imported their
     * current versions yet. Returns the number of questions added; 0 means
     * already imported, storage not ready, or the assets are unusable.
     *
     * Runs on the caller's thread: [PolicyProduct] calls this off the main
     * thread because the full 1–9 banks are large, and it happens once per
     * seed version before the lock screen reads the bank for the first time.
     * The import holds the cache lock while it parses; queries on other
     * threads wait for it to finish just as they would for the insert.
     */
    @Synchronized
    fun install(context: Context): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        return installAsset(context, ASSET, SEED_VERSION, SEED_TAG, KEY_VERSION) +
            installAsset(
                context,
                MULTI_ASSET,
                MULTI_SEED_VERSION,
                MULTI_SEED_TAG,
                KEY_MULTI_VERSION,
            ) +
            installAsset(
                context,
                PARENT_FUN_ASSET,
                PARENT_FUN_VERSION,
                PARENT_FUN_TAG,
                KEY_PARENT_FUN_VERSION,
            )
    }

    @VisibleForTesting
    internal fun installSingle(context: Context): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        return installAsset(context, ASSET, SEED_VERSION, SEED_TAG, KEY_VERSION)
    }

    @VisibleForTesting
    internal fun installMulti(context: Context): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        return installAsset(context, MULTI_ASSET, MULTI_SEED_VERSION, MULTI_SEED_TAG, KEY_MULTI_VERSION)
    }

    @VisibleForTesting
    internal fun installParentFun(context: Context): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        return installAsset(
            context,
            PARENT_FUN_ASSET,
            PARENT_FUN_VERSION,
            PARENT_FUN_TAG,
            KEY_PARENT_FUN_VERSION,
        )
    }

    private fun installAsset(
        context: Context,
        asset: String,
        version: Int,
        tag: String,
        markerKey: String,
    ): Int {
        if (version <= 0 || TvStore.getInt(markerKey, 0) >= version) return 0
        return try {
            context.applicationContext.assets.open(asset).bufferedReader().use { reader ->
                importReader(reader, version, System.currentTimeMillis(), tag, markerKey)
            }
        } catch (error: FileNotFoundException) {
            // The multiple-choice bank is generated separately and may not be
            // bundled in this build yet. Leave the marker unset so a later APK
            // that includes the asset can still import it.
            0
        } catch (error: Exception) {
            Log.e(TAG, "cannot read $asset", error)
            0
        }
    }

    @VisibleForTesting
    internal fun importJson(
        raw: String,
        version: Int,
        nowMs: Long = System.currentTimeMillis(),
        tag: String = SEED_TAG,
        markerKey: String = KEY_VERSION,
    ): Int = importReader(StringReader(raw), version, nowMs, tag, markerKey)

    @VisibleForTesting
    internal fun importMultiJson(
        raw: String,
        version: Int,
        nowMs: Long = System.currentTimeMillis(),
    ): Int = importJson(raw, version, nowMs, MULTI_SEED_TAG, KEY_MULTI_VERSION)

    @VisibleForTesting
    internal fun importParentFunJson(
        raw: String,
        version: Int,
        nowMs: Long = System.currentTimeMillis(),
    ): Int = importJson(raw, version, nowMs, PARENT_FUN_TAG, KEY_PARENT_FUN_VERSION)

    private fun importReader(
        reader: Reader,
        version: Int,
        nowMs: Long,
        tag: String,
        markerKey: String,
    ): Int {
        if (!TvStore.isReady || !QuizQuestionCache.isReady()) return 0
        if (version <= 0 || TvStore.getInt(markerKey, 0) >= version) return 0
        val json = JsonReader(reader)
        var hasItems = false
        var skipped = 0
        val items = readItems(
            json,
            onItems = { hasItems = true },
            onSkipped = { skipped++ },
        )
        val result = QuizQuestionCache.replaceSeedQuestionsStreaming(
            batchId = "$tag$version",
            items = items,
            nowMs = nowMs,
            sourceRefPrefix = tag,
        )
        if (!hasItems) {
            Log.e(TAG, "$tag v$version has no items array")
            return 0
        }
        if (result.appended == 0 && result.duplicates == 0) {
            // Nothing usable made it in. Leave the marker unset so a later
            // start can retry instead of freezing an empty seed bank.
            Log.w(
                TAG,
                "$tag v$version imported nothing: rejected=${result.rejected} skipped=$skipped",
            )
            return 0
        }
        // A partial import (the bank is already full of user questions) still
        // marks the version. Otherwise every start would delete and reinsert
        // the same seed rows, resetting their answer history each time.
        TvStore.putInt(markerKey, version)
        TvStore.sync()
        Log.i(
            TAG,
            "$tag v$version: appended=${result.appended} " +
                "duplicates=${result.duplicates} rejected=${result.rejected} skipped=$skipped",
        )
        return result.appended
    }

    /**
     * Lazily reads the root object and yields each usable item in its `items`
     * array. The caller's cache transaction consumes the sequence; a parse
     * error surfaces from there and rolls back the transaction.
     */
    private fun readItems(
        reader: JsonReader,
        onItems: () -> Unit,
        onSkipped: () -> Unit,
    ): Sequence<QuizItem> = sequence {
        if (reader.peek() != JsonToken.BEGIN_OBJECT) return@sequence
        reader.beginObject()
        while (reader.hasNext()) {
            when (reader.nextName()) {
                "items" -> {
                    onItems()
                    reader.beginArray()
                    while (reader.hasNext()) {
                        val encoded = readJsonObject(reader).toString()
                        val item = QuizSessionCodec.decodeItem(encoded)
                        if (item == null) onSkipped() else yield(item)
                    }
                    reader.endArray()
                }
                else -> reader.skipValue()
            }
        }
        reader.endObject()
    }

    private fun readJsonObject(reader: JsonReader): JSONObject {
        val json = JSONObject()
        reader.beginObject()
        while (reader.hasNext()) {
            val name = reader.nextName()
            json.put(name, readJsonValue(reader))
        }
        reader.endObject()
        return json
    }

    private fun readJsonArray(reader: JsonReader): JSONArray {
        val json = JSONArray()
        reader.beginArray()
        while (reader.hasNext()) {
            json.put(readJsonValue(reader))
        }
        reader.endArray()
        return json
    }

    private fun readJsonValue(reader: JsonReader): Any {
        val token = reader.peek()
        return when (token) {
            JsonToken.BEGIN_OBJECT -> readJsonObject(reader)
            JsonToken.BEGIN_ARRAY -> readJsonArray(reader)
            JsonToken.STRING -> reader.nextString()
            JsonToken.NUMBER -> {
                // The codec requires real JSON numbers: `answerIndices` is
                // rejected when an entry is a String, even if it looks like an
                // integer. Keep integers integral and fall back to Double for
                // decimals and values outside the Long range.
                val raw = reader.nextString()
                raw.toLongOrNull()?.let { value ->
                    if (value in Int.MIN_VALUE..Int.MAX_VALUE) value.toInt() else value
                } ?: raw.toDouble()
            }
            JsonToken.BOOLEAN -> reader.nextBoolean()
            JsonToken.NULL -> {
                reader.nextNull()
                JSONObject.NULL
            }
            else -> throw IllegalStateException("unexpected JSON token $token")
        }
    }

    @VisibleForTesting
    internal fun clearMarkerForTest() {
        TvStore.remove(KEY_VERSION)
        TvStore.remove(KEY_MULTI_VERSION)
        TvStore.remove(KEY_PARENT_FUN_VERSION)
    }
}
