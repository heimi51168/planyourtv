package com.planyourtv.policy

/**
 * Deterministic output of the rule scheduler. A [Start] carries one immutable plan; the caller
 * hands it to the shared executor. Everything else is the lock state before a plan exists.
 */
sealed interface RulePlanDecision {
    data object SetupRequired : RulePlanDecision

    data class Locked(
        val reason: LockReason,
        /** 0 = today, 1 = tomorrow; -1 when no future window exists. */
        val nextWindowDayOffset: Int = -1,
        /** Minute of day for the next window start; -1 when none. */
        val nextWindowMinuteOfDay: Int = -1,
        val breakRemainingSeconds: Long = 0,
    ) : RulePlanDecision

    data class Start(
        val plan: PolicyExecutionPlan,
        val window: LocalTimeWindow,
        /** Seconds left in the window at decision time; it does not cap the plan. */
        val windowRemainingSeconds: Long,
        val dailyRemainingSeconds: Long,
    ) : RulePlanDecision
}

/**
 * Rule plan producer. It is deliberately pure: the caller owns the clock, the local day ledger,
 * rest persistence and the rule template version. The decision core stays [LocalScheduleEngine]
 * so the rule editor and the remote mirror keep the same window/limit semantics.
 */
object RulePlanScheduler {
    /**
     * @param dayOfWeek 1 = Monday ... 7 = Sunday
     * @param secondOfDay 0 until 86400
     * @param templateVersion rules version snapshot; 0 when the TV has no version yet
     * @param sessionId stable rule usage id generated by the caller when a plan starts
     * @param usedSecondsToday already ended sessions for the TV's local date
     * @param breakRemainingSeconds wall-clock rest left; zero when no rest is active
     * @param accessMode/allowedPackages rule-mode global app scope snapshot
     */
    fun decide(
        dayOfWeek: Int,
        secondOfDay: Int,
        rules: LocalRules,
        templateVersion: Long,
        sessionId: String,
        usedSecondsToday: Long,
        breakRemainingSeconds: Long = 0,
        accessMode: AccessMode = AccessMode.SCREEN,
        allowedPackages: Set<String> = emptySet(),
    ): RulePlanDecision {
        val decision = LocalScheduleEngine.evaluate(
            dayOfWeek = dayOfWeek,
            secondOfDay = secondOfDay,
            rules = rules,
            usedSecondsToday = usedSecondsToday,
            breakRemainingSeconds = breakRemainingSeconds,
        )
        return when (decision) {
            is LocalDecision.SetupRequired -> RulePlanDecision.SetupRequired
            is LocalDecision.Locked -> RulePlanDecision.Locked(
                reason = decision.reason,
                nextWindowDayOffset = decision.nextWindowDayOffset,
                nextWindowMinuteOfDay = decision.nextWindowMinuteOfDay,
                breakRemainingSeconds = decision.breakRemainingSeconds,
            )
            is LocalDecision.Active -> {
                val window = rules.windowsFor(dayOfWeek)
                    .firstOrNull { it.contains(secondOfDay) }
                    ?: return RulePlanDecision.Locked(LockReason.OUTSIDE_WINDOW)
                require(sessionId.isNotBlank()) { "rule plans need a session id" }
                val endReason = when (decision.endReason) {
                    LocalSessionEnd.SESSION_LIMIT -> PolicyEndReason.SESSION_LIMIT
                    LocalSessionEnd.DAILY_LIMIT -> PolicyEndReason.DAILY_LIMIT
                    LocalSessionEnd.WINDOW_END -> PolicyEndReason.WINDOW_END
                }
                val restAfterSeconds =
                    if (endReason == PolicyEndReason.SESSION_LIMIT) rules.restMinutes * 60L else 0L
                val plan = PolicyExecutionPlan(
                    id = sessionId,
                    source = PolicyPlanSource.RULE,
                    activation = PolicyActivation.AUTO,
                    endReason = endReason,
                    budgetSeconds = decision.sessionSeconds,
                    // A window only decides whether a session may start. Give the segment no
                    // window deadline so it can finish after the window closes; the executor
                    // still caps it by its budget and local midnight.
                    deadlineEpochMs = null,
                    accessMode = accessMode,
                    allowedPackages = allowedPackages,
                    restAfterSeconds = restAfterSeconds,
                    templateVersion = templateVersion,
                    sessionId = sessionId,
                )
                RulePlanDecision.Start(
                    plan = plan,
                    window = window,
                    windowRemainingSeconds = decision.windowRemainingSeconds,
                    dailyRemainingSeconds = decision.dailyRemainingSeconds,
                )
            }
        }
    }
}
